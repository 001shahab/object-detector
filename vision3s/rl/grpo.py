"""Group Relative Policy Optimization (Sec. 3.3, Eqs. 4–5).

For each query and initial state, ``G`` trajectories are sampled from
``π_θold``. The group-relative advantage is::

    A_i = (R(τ_i) - μ_R) / (σ_R + ε)                                  (4)

and the objective, averaged over the ``T_i`` policy tokens of each trajectory
and then over the group, is::

    J = 1/G Σ_i 1/T_i Σ_t [min(r_{i,t} A_i, clip(r_{i,t}, 1-ε_c, 1+ε_c) A_i) - β D_KL^{i,t}]   (5)

with ``r_{i,t} = π_θ / π_θold`` and a token-level KL penalty to the reference
policy. Only tokens generated by the policy (assistant turns) are optimised;
system, user and tool-response tokens are masked out.
"""

from __future__ import annotations

from collections import defaultdict
from typing import Sequence

import torch


def group_advantages(rewards: Sequence[float], groups: Sequence, eps: float = 1e-6, clip: float | None = None) -> list[float]:
    """Eq. 4 per group of trajectories that share a query and initial state."""
    by_group: dict = defaultdict(list)
    for i, g in enumerate(groups):
        by_group[g].append(i)
    adv = [0.0] * len(rewards)
    for idx in by_group.values():
        r = torch.tensor([float(rewards[i]) for i in idx], dtype=torch.float64)
        std = r.std() if len(idx) > 1 else torch.tensor(0.0, dtype=torch.float64)
        a = (r - r.mean()) / (std + eps)
        if clip is not None:
            a = a.clamp(-clip, clip)
        for i, v in zip(idx, a.tolist()):
            adv[i] = v
    return adv


def kl_penalty(logp: torch.Tensor, ref_logp: torch.Tensor, kind: str = "low_var_kl") -> torch.Tensor:
    """Per-token KL estimate of ``π_θ || π_ref``."""
    log_ratio = ref_logp - logp
    if kind == "low_var_kl":  # k3 estimator, unbiased and non-negative
        return (torch.exp(log_ratio) - log_ratio - 1.0).clamp(-10.0, 10.0)
    if kind == "kl":  # k1
        return -log_ratio
    if kind == "mse":  # k2
        return 0.5 * log_ratio.square()
    raise ValueError(f"unknown KL estimator {kind!r}")


def grpo_token_loss(logp: torch.Tensor, old_logp: torch.Tensor, ref_logp: torch.Tensor | None, advantage: float,
                    clip_eps: float = 0.2, kl_coef: float = 0.001, kl_type: str = "low_var_kl",
                    entropy: torch.Tensor | None = None, entropy_coef: float = 0.0) -> tuple[torch.Tensor, dict]:
    """Negative of the per-trajectory term of Eq. 5 (token mean over one trajectory)."""
    ratio = torch.exp(logp - old_logp)
    adv = torch.as_tensor(advantage, dtype=logp.dtype, device=logp.device)
    surrogate = torch.minimum(ratio * adv, ratio.clamp(1.0 - clip_eps, 1.0 + clip_eps) * adv)
    per_token = -surrogate
    stats = {"clipfrac": ((ratio - 1.0).abs() > clip_eps).float().mean().item(), "ratio": ratio.mean().item()}
    if ref_logp is not None and kl_coef:
        kl = kl_penalty(logp, ref_logp, kl_type)
        per_token = per_token + kl_coef * kl
        stats["kl"] = kl.mean().item()
    if entropy is not None and entropy_coef:
        per_token = per_token - entropy_coef * entropy
        stats["entropy"] = entropy.mean().item()
    return per_token.mean(), stats


def assistant_token_mask(input_ids: torch.Tensor, im_start_id: int, assistant_ids: Sequence[int],
                         im_end_id: int) -> torch.Tensor:
    """Mask of tokens inside assistant turns: everything after ``<|im_start|>assistant\\n`` up to and
    including the closing ``<|im_end|>``."""
    ids = input_ids.tolist()
    mask = torch.zeros_like(input_ids, dtype=torch.bool)
    header = [im_start_id, *assistant_ids]
    i, n = 0, len(ids)
    while i < n:
        if ids[i:i + len(header)] == header:
            j = i + len(header)
            while j < n and ids[j] != im_end_id:
                mask[j] = True
                j += 1
            if j < n:
                mask[j] = True
            i = j + 1
        else:
            i += 1
    return mask
